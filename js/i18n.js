// Global i18n manager
class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('jordan_saloon_lang');
    this.init();
  }

  init() {
    if (this.currentLang && translations[this.currentLang]) {
      this.setLanguage(this.currentLang);
    } else {
      // Show mandatory splash language selector
      this.showLanguageModal();
      this.setLanguage('ar'); // default before choice
    }
    this.bindEvents();
  }

  showLanguageModal() {
    const modal = document.getElementById('langChoiceModal');
    if (modal) {
      modal.classList.add('active');
      document.body.style.overflow = 'hidden';
      const modalVideo = modal.querySelector('.lang-modal-video');
      if (modalVideo) {
        modalVideo.play().catch(() => { });
      }
    }
  }

  hideLanguageModal() {
    const modal = document.getElementById('langChoiceModal');
    if (modal) {
      modal.classList.remove('active');
      document.body.style.overflow = '';

      // Ensure hero video is playing seamlessly
      const heroVideo = document.getElementById('heroVideo');
      if (heroVideo && heroVideo.paused) {
        heroVideo.play().catch(() => { });
      }
    }
  }

  bindEvents() {
    document.querySelectorAll('.lang-btn, .lang-modal-choice-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const lang = e.currentTarget.getAttribute('data-lang');
        if (lang && translations[lang]) {
          this.setLanguage(lang);
          this.hideLanguageModal();
        }
      });
    });
  }

  setLanguage(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('jordan_saloon_lang', lang);

    const isRTL = lang === 'ar' || lang === 'ku';
    const htmlEl = document.documentElement;

    htmlEl.setAttribute('lang', lang);
    htmlEl.setAttribute('dir', isRTL ? 'rtl' : 'ltr');

    if (isRTL) {
      document.body.classList.add('rtl-mode');
    } else {
      document.body.classList.remove('rtl-mode');
    }

    // Update active state in language switchers
    document.querySelectorAll('.lang-btn').forEach(btn => {
      if (btn.getAttribute('data-lang') === lang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // Translate all elements with data-i18n
    const dict = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.setAttribute('placeholder', dict[key]);
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Translate placeholder attributes specifically
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Update dynamic document title & meta description
    if (dict.meta_title) document.title = dict.meta_title;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && dict.meta_desc) metaDesc.setAttribute('content', dict.meta_desc);

    // Notify custom listeners
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, isRTL } }));
  }

  getText(key) {
    return translations[this.currentLang]?.[key] || translations['en'][key] || key;
  }

  getArabicService(serviceKey) {
    return translations['ar'][serviceKey] || serviceKey;
  }
}

window.I18n = new I18nManager();
window.i18n = window.I18n;
window.i18n.t = (key, fallback) => window.I18n.getText(key) || fallback;
